#!/usr/bin/env python3
"""Export the APB runtime palette; --check detects stale handoff snapshots."""
import argparse
import hashlib
import json
from pathlib import Path
import re

PACK = Path(__file__).resolve().parents[1]
REPO = PACK.parent
SOURCE = REPO / 'platform/app/static/admin.css'


def outputs():
    css = SOURCE.read_text(encoding='utf-8')
    palette = dict(re.findall(r'(--apb-[\w-]+):\s*([^;]+);', css.split('}', 1)[0]))
    names = {'primary': 'red', 'primary-hover': 'red-dark', 'ink': 'ink',
             'text': 'text', 'muted': 'muted', 'line': 'line', 'surface': 'panel',
             'background': 'bg', 'success': 'success', 'success-bg': 'success-bg',
             'warning': 'warn', 'warning-bg': 'warn-bg', 'danger': 'danger', 'danger-bg': 'danger-bg'}
    tokens = {name: {'value': palette['--apb-' + key], 'source': '--apb-' + key}
              for name, key in names.items()}
    # Source selectors are deliberately explicit: changes require review, not silent fallback.
    specs = {
        'font-sans': (r'body\s*\{(.*?)\}', r'font-family:\s*([^;]+);'),
        'font-mono': (r'code,\s*\.mono\s*\{(.*?)\}', r'font-family:\s*([^;]+);'),
        'font-body': (r'body\s*\{(.*?)\}', r'font-size:\s*([^;]+);'),
        'control-height': (r'input, select, textarea\s*\{(.*?)\}', r'min-height:\s*([^;]+);'),
        'control-radius': (r'input, select, textarea\s*\{(.*?)\}', r'border-radius:\s*([^;]+);'),
        'panel-radius': (r'\.panel\s*\{(.*?)\}', r'border-radius:\s*([^;]+);'),
    }
    for name, (selector, prop) in specs.items():
        block = re.search(selector, css, re.S)
        if not block or not (match := re.search(prop, block[1])):
            raise ValueError(f'APB source changed: review {name}')
        tokens[name] = {'value': match[1].strip(), 'source': 'admin.css selector: ' + selector}
    extra = json.loads((PACK / 'extension-tokens.json').read_text(encoding='utf-8'))
    for name, value in extra.items():
        tokens[name] = {'value': value, 'source': 'extension-tokens.json'}
    lines = ['/* Generated by tools/build_tokens.py; load before apb-erp.css. */', '[data-apb-erp] {']
    for name, token in tokens.items():
        value = token['value']
        if token['source'].startswith('--apb-'):
            value = f"var({token['source']}, {value})"
        lines.append(f'  --apb-erp-{name}: {value};')
    lines += ['}', '']
    manifest = {'schema': 'apb-liteerp-style/1', 'reviewed': '2026-10-20',
                'source': 'platform/app/static/admin.css',
                'source_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(), 'tokens': tokens}
    return {'assets/tokens.css': '\n'.join(lines),
            'tokens.json': json.dumps(manifest, ensure_ascii=False, indent=2) + '\n',
            'preview/host-reference.css': '/* Offline reference only. Never load in the ERP module. */\n' + css}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, value in outputs().items():
        path = PACK / name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != value:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value, encoding='utf-8')
    if stale:
        raise SystemExit('Stale exports: ' + ', '.join(stale))
    print('APB token snapshot: ' + ('verified' if args.check else 'generated'))
